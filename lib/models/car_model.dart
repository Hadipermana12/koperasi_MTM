class CarModel {
  final String id;
  final String name;
  final String type;
  final double pricePerDay;
  final String image;
  final String transmission;
  final int capacity;
  final String fuel;

  CarModel({
    required this.id,
    required this.name,
    required this.type,
    required this.pricePerDay,
    required this.image,
    required this.transmission,
    required this.capacity,
    required this.fuel,
  });
}
